#!/bin/bash
# install_server.sh
# Install the DataReel Reporting Agent for Linux PHP pages on a web server.
#
# Usage: install_server.sh [--apply] [--admin-user NAME] [--drsm-login CONFIG]
#                          WEB_DIR DATA_DIR
#
#   WEB_DIR   Web directory for the pages, for example
#             /var/www/html/linux. The pages go in WEB_DIR/upload/
#             (register.php, upload.php, admin.php).
#   DATA_DIR  Directory for server.ini, agent registrations and reports.
#             Best outside the web root. If it is inside WEB_DIR (common on
#             shared hosting), a "Require all denied" .htaccess is added.
#
#   --apply       Make the changes. Without it the script only shows what
#                 it would do (dry run).
#   --admin-user  Create DATA_DIR/admin.htpasswd with this user (htpasswd
#                 asks for the password) if the file does not exist.
#   --drsm-login  Use the DataReel System Monitor dashboard login instead
#                 of a web server login. CONFIG is the dashboard's
#                 config/drsm.php. WEB_DIR must be under the dashboard's
#                 web folder, for example <dashboard>/linux.
#
# The script never overwrites an existing server.ini or admin.htpasswd.
# The web server user must be able to write to DATA_DIR; the script prints
# the commands for that at the end.

APPLY=0
ADMIN_USER=""
DRSM_CONFIG=""
while [ $# -gt 0 ]; do
    case "$1" in
	--apply) APPLY=1; shift ;;
	--admin-user) ADMIN_USER="$2"; shift 2 ;;
	--drsm-login) DRSM_CONFIG="$2"; shift 2 ;;
	-h|--help) sed -n '2,29p' "$0" | sed 's/^# \{0,1\}//'; exit 0 ;;
	-*) echo "Unknown option $1"; exit 1 ;;
	*) break ;;
    esac
done

if [ $# -ne 2 ]; then
    echo "Usage: $0 [--apply] [--admin-user NAME] [--drsm-login CONFIG] WEB_DIR DATA_DIR"
    exit 1
fi

WEB_DIR="${1%/}"
DATA_DIR="${2%/}"
SRC_DIR="$(cd "$(dirname "$0")" && pwd)"
PAGES="register.php upload.php admin.php lra_lib.php lra_auth.php"

case "$WEB_DIR" in /*) ;; *) echo "WEB_DIR must be an absolute path"; exit 1 ;; esac
case "$DATA_DIR" in /*) ;; *) echo "DATA_DIR must be an absolute path"; exit 1 ;; esac

if [ ${APPLY} -eq 0 ]; then
    echo "DRY RUN - nothing will be changed. Run again with --apply to install."
    RSYNC_OPTS="-n"
else
    RSYNC_OPTS=""
fi

run() {
    echo "+ $*"
    if [ ${APPLY} -eq 1 ]; then
	"$@" || { echo "ERROR - command failed"; exit 1; }
    fi
}

# Write stdin to a file, or show it on a dry run
write_file() {
    local dest="$1"
    if [ ${APPLY} -eq 1 ]; then
	cat > "${dest}" || { echo "ERROR - could not write ${dest}"; exit 1; }
	echo "Wrote ${dest}"
    else
	echo "Would write ${dest}:"
	sed 's/^/    /'
    fi
}

run mkdir -p "${WEB_DIR}/upload" "${DATA_DIR}/agents" "${DATA_DIR}/nonces" "${DATA_DIR}/reports"

echo "Copying pages to ${WEB_DIR}/upload"
for f in ${PAGES}; do
    if [ ${APPLY} -eq 0 ] && [ ! -d "${WEB_DIR}/upload" ]; then
	echo "Would copy ${f} (new)"
	continue
    fi
    rsync -av ${RSYNC_OPTS} "${SRC_DIR}/${f}" "${WEB_DIR}/upload/${f}" | grep -v '^sending\|^sent\|^total\|^$'
done

if [ "${DRSM_CONFIG}" != "" ]; then
    write_file "${WEB_DIR}/upload/.htaccess" <<EOF
# Generated by install_server.sh
SetEnv LRA_SERVER_INI ${DATA_DIR}/server.ini

# Only included by the other pages
<FilesMatch "^lra_(lib|auth)\.php$">
    Require all denied
</FilesMatch>

# admin.php uses the DRSM dashboard login
# (login = drsm in server.ini)
EOF
else
    write_file "${WEB_DIR}/upload/.htaccess" <<EOF
# Generated by install_server.sh
SetEnv LRA_SERVER_INI ${DATA_DIR}/server.ini

# Only included by the other pages
<FilesMatch "^lra_(lib|auth)\.php$">
    Require all denied
</FilesMatch>

# The admin page needs a login
<FilesMatch "^admin\.php$">
    AuthType Basic
    AuthName "DataReel Reporting Agent for Linux admin"
    AuthUserFile ${DATA_DIR}/admin.htpasswd
    Require valid-user
</FilesMatch>
EOF
fi

# PHP's default upload limit (2M) is below the size of an OpenSCAP HTML
# report. .user.ini works with php-fpm (RHEL 8 and later), the .htaccess
# php_value lines with mod_php.
write_file "${WEB_DIR}/upload/.user.ini" <<EOF
; Generated by install_server.sh: room for OpenSCAP HTML reports
upload_max_filesize = 24M
post_max_size = 48M
EOF

case "${DATA_DIR}/" in
    "${WEB_DIR}/"*)
	echo "DATA_DIR is inside WEB_DIR, blocking web access to it"
	write_file "${DATA_DIR}/.htaccess" <<EOF
# Generated by install_server.sh: registrations, reports and settings
Require all denied
EOF
	;;
esac

if [ -f "${DATA_DIR}/server.ini" ]; then
    echo "Keeping existing ${DATA_DIR}/server.ini"
else
    login_sed=()
    if [ "${DRSM_CONFIG}" != "" ]; then
	login_sed=(-e "s#^login = .*#login = drsm#" -e "s#^drsm_config =.*#drsm_config = ${DRSM_CONFIG}#")
    fi
    sed -e "s#^reports_dir = .*#reports_dir = ${DATA_DIR}/reports#" \
	-e "s#^data_dir = .*#data_dir = ${DATA_DIR}#" "${login_sed[@]}" \
	"${SRC_DIR}/server.ini.example" | write_file "${DATA_DIR}/server.ini"
fi

if [ "${ADMIN_USER}" != "" ]; then
    if [ -f "${DATA_DIR}/admin.htpasswd" ]; then
	echo "Keeping existing ${DATA_DIR}/admin.htpasswd"
    else
	run htpasswd -c -B "${DATA_DIR}/admin.htpasswd" "${ADMIN_USER}"
    fi
fi

cat <<EOF

Next steps:
 - Let the web server user write to ${DATA_DIR}, for example:
     setfacl -R -m u:apache:rwX -m d:u:apache:rwX ${DATA_DIR}
   With SELinux enforcing, also:
     semanage fcontext -a -t httpd_sys_rw_content_t "${DATA_DIR}(/.*)?"
     restorecon -R ${DATA_DIR}
 - Edit ${DATA_DIR}/server.ini (enrollment token, approval policy)
 - Create the admin login if you have not: htpasswd -c -B ${DATA_DIR}/admin.htpasswd <user>
 - Point the agents at the pages, in drra.ini [https]:
     upload_path   = <url path of ${WEB_DIR}>/upload/upload.php
     register_path = <url path of ${WEB_DIR}>/upload/register.php
EOF
exit 0
